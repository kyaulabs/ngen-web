// Reuse the repository's loopback-only allowlisted test server. No production
// service, downloaded executable, external font or new npm dependency is needed.
const server = spawn(process.execPath, ['tests/server.mjs'], { cwd: root, stdio: ['ignore', 'inherit', 'inherit', 'ipc'] });
let browser;
let readinessTimeout;
const ready = new Promise((resolve, reject) => {
  readinessTimeout = setTimeout(() => reject(new Error('Brand guide server did not become ready.')), 5000);
  server.once('message', (message) => message === 'ready' ? resolve() : reject(new Error('Unexpected server readiness message.')));
  server.once('error', reject);
  server.once('exit', () => reject(new Error('Brand export test server could not start; port 4173 must be free.')));
});
try {
  await ready.finally(() => clearTimeout(readinessTimeout));
  browser = await chromium.launch();
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  await page.route('**/*', (route) => {
    const url = new URL(route.request().url());
    return url.origin === 'http://127.0.0.1:4173' && url.pathname.startsWith('/brand/') ? route.continue() : route.abort();
  });
  await page.goto('http://127.0.0.1:4173/brand/guide/ngen-brand-guide.html', { waitUntil: 'networkidle' });
  await page.emulateMedia({ media: 'print' });
  await page.evaluate(() => document.fonts.ready);
  const layout = await page.evaluate(() => ({
    pages: document.querySelectorAll('.page').length,
    clipped: [...document.querySelectorAll('.content')].filter((element) => element.scrollHeight > element.clientHeight + 1 || element.scrollWidth > element.clientWidth + 1).map((element) => element.closest('.page').getAttribute('aria-label')),
    images: [...document.images].filter((image) => !image.complete || !image.naturalWidth).map((image) => image.getAttribute('src')),
  }));
  if (errors.length || layout.pages !== 11 || layout.clipped.length || layout.images.length) throw new Error(JSON.stringify({ errors, layout }));
  await page.pdf({ path: path('brand/guide/ngen-brand-guide.pdf'), printBackground: true, preferCSSPageSize: true, tagged: true });
} finally {
  try {
    await browser?.close();
  } finally {
    if (server.pid && server.exitCode === null && server.signalCode === null) {
      const closed = once(server, 'close');
      server.kill();
      await closed;
    }
  }
}
