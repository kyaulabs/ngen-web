// Optional brand-authoring tooling, not part of the website build or runtime.
import { readFile, writeFile, readdir, mkdtemp, rm } from 'node:fs/promises';
import { execFile, spawn } from 'node:child_process';
import { once } from 'node:events';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from '@playwright/test';

const root = fileURLToPath(new URL('../', import.meta.url));
const path = (name) => `${root}${name}`;
const execute = promisify(execFile);
const tokens = JSON.parse(await readFile(path('brand/web/ngen-tokens.json'), 'utf8'));
const xml = (value) => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
function paint(value, property = 'fill') {
  if (/^#[\da-f]{6}$/i.test(value)) return `${property}="${value}"`;
  const match = /^color-mix\(in srgb, (#[\da-f]{6}) (\d+(?:\.\d+)?)%, transparent\)$/i.exec(value);
  if (!match || Number(match[2]) > 100) throw new Error(`Unsupported brand paint: ${value}`);
  return `${property}="${match[1]}" ${property}-opacity="${Number(match[2]) / 100}"`;
}
for (const theme of Object.values(tokens.themes)) for (const value of Object.values(theme)) paint(value);
for (const theme of Object.values(tokens.components)) for (const value of Object.values(theme)) paint(value);
const fontFaces = (await readFile(path('styles.scss'), 'utf8')).match(/^@font-face .*$/gm);
if (fontFaces?.length !== 16) throw new Error('Expected the sixteen supplied Prism font faces.');
const declarations = (mode) => [
  `  color-scheme: ${mode};`,
  ...Object.entries(tokens.themes[mode]).map(([key, value]) => `  --ngen-${key}: ${value};`),
  ...Object.entries(tokens.components[mode]).map(([key, value]) => `  --${key}: ${value};`),
].join('\n');
await writeFile(path('brand/web/ngen-theme.css'), `/* NGEN ${tokens.version}. Generated by npm run build:brand from ngen-tokens.json and styles.scss font faces. */
${fontFaces.join('\n').replaceAll('brand/web/fonts/', 'fonts/')}
:root {
${declarations('light')}
  --ngen-font-sans: ${tokens.typography.sans};
  --ngen-font-mono: ${tokens.typography.mono};
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${declarations('dark')}
  }
}
:root[data-theme="dark"] {
${declarations('dark')}
}
`);

// Preserve both 1240×850 canvases and the five-column grid; five shorter rows
// accommodate Prism's tertiary/subtle pigments and distinct border materials.
for (const mode of ['dark', 'light']) {
  const theme = tokens.themes[mode], materials = tokens.components[mode];
  const rect = (x, y, w, h, fill, radius = 7) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" ${paint(fill)} ${paint(materials.line, 'stroke')}/>`;
  const text = (x, y, value, size, fill = theme.muted, mono = true, weight = mono ? 500 : 400) => `<text x="${x}" y="${y}" fill="${fill}" font-family="${mono ? 'Operator Mono, monospace' : 'Neo Sans Pro, sans-serif'}" font-size="${size}" font-weight="${weight}">${xml(value)}</text>`;
  const samples = [
    ...Object.entries(theme).map(([key, value]) => [key, value, value]),
    ...['panel', 'panel-2', 'line', 'line-strong'].map((key) => {
      const value = materials[key], match = /(#\w+) ([\d.]+)%/.exec(value);
      return [key, value, match ? `${match[1]} / ${match[2]}%` : value];
    }),
  ];
  if (samples.length > 25) throw new Error('Palette sheet exceeds its five-row canvas.');
  const cards = samples.map(([key, value, label], index) => {
    const x = 48 + index % 5 * 231, y = 194 + Math.floor(index / 5) * 118;
    return rect(x, y, 220, 104, materials.panel) + rect(x + 12, y + 10, 196, 43, value, 5)
      + text(x + 13, y + 77, key, 15, theme.text) + text(x + 13, y + 96, label, 12);
  }).join('\n');
  await writeFile(path(`brand/web/palettes/ngen-palette-${mode}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1240 850" width="1240" height="850" role="img" aria-labelledby="title"><title id="title">NGEN ${mode} base colors and translucent materials</title>
<rect width="1240" height="850" fill="${theme.bg}"/>
<rect x="48" y="36" width="6" height="15" rx="1" fill="${theme.accent}"/>
${text(66, 50, 'KYAU LABS / NGEN WEBSITE THEME', 15)}
${text(46, 114, `${mode === 'dark' ? 'Dark' : 'Light'} palette`, 60, theme.text, false, 700)}
${text(48, 151, 'Prism-derived colors. Component aliases carry background and border alpha.', 21, theme.muted, false)}
<path d="M48 173H1192M48 801H1192" ${paint(materials.line, 'stroke')}/>
${cards}
${text(48, 827, `NGEN / THEME TOKENS ${tokens.version}`, 14)}
</svg>\n`);
}

// Isolate authoring fonts/cache; do not install fonts or change host settings.
const workspace = await mkdtemp(join(tmpdir(), 'ngen-brand-fonts-'));
const config = join(workspace, 'fonts.conf');
await writeFile(config, `<?xml version="1.0"?><!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd"><fontconfig><include>/etc/fonts/fonts.conf</include><dir>${xml(path('brand/web/fonts'))}</dir><cachedir>${xml(workspace)}</cachedir><alias><family>Operator Mono</family><prefer><family>OperatorMonoLig Nerd Font</family><family>OperatorMonoSSmLig Nerd Font</family></prefer></alias></fontconfig>`);
const env = { ...process.env, FONTCONFIG_FILE: config, XDG_CACHE_HOME: workspace };
const run = (name, args) => execute(name, args, { env });
try {
  // Rebuild every colored raster counterpart at its existing dimensions.
  // Monochrome assets are intentionally not regenerated.
  const files = await readdir(path('brand'), { recursive: true });
  for (const name of files.filter((name) => name.endsWith('.png') && !name.startsWith('guide/') && !name.includes('-mono-'))) {
    let master = name.replace(/\.png$/, '.svg');
    if (/^(?:icons\/(?:app|favicon)|icons\/png|logos\/png)\//.test(name)) master = master.replace(/-\d+\.svg$/, '.svg').replace('/png/', '/svg/');
    const dimensions = (await run('magick', ['identify', '-format', '%w %h', path(`brand/${name}`)])).stdout.trim();
    if (!/^\d{1,5} \d{1,5}$/.test(dimensions)) throw new Error(`Invalid raster dimensions: ${name}`);
    const [width, height] = dimensions.split(' ');
    await run('rsvg-convert', ['--keep-aspect-ratio', '--width', width, '--height', height, '--output', path(`brand/${name}`), path(`brand/${master}`)]);
  }
  for (const mode of ['dark', 'light']) await run('magick', [...[16, 32, 48].map((size) => path(`brand/icons/favicon/favicon-${mode}-${size}.png`)), path(`brand/icons/favicon/favicon-${mode}.ico`)]);

  const server = spawn(process.execPath, ['tests/server.mjs'], { cwd: root, stdio: ['ignore', 'inherit', 'inherit', 'ipc'] });
  let browser;
  let readinessTimeout;
  const ready = new Promise((resolve, reject) => {
    readinessTimeout = setTimeout(() => reject(new Error('Brand guide server did not become ready.')), 5000);
    server.once('message', (message) => message === 'ready' ? resolve() : reject(new Error('Unexpected server readiness message.')));
    server.once('error', reject);
    server.once('exit', () => reject(new Error('Brand export test server could not start; port 4173 must be free.')));
  });
  try {
    await ready.finally(() => clearTimeout(readinessTimeout));
    browser = await chromium.launch({ env });
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    await page.route('**/*', (route) => {
      const url = new URL(route.request().url());
      return url.origin === 'http://127.0.0.1:4173' && url.pathname.startsWith('/brand/') ? route.continue() : route.abort();
    });
    await page.goto('http://127.0.0.1:4173/brand/guide/ngen-brand-guide.html', { waitUntil: 'networkidle' });
    await page.emulateMedia({ media: 'print' });
    await page.evaluate(() => document.fonts.ready);
    const layout = await page.evaluate(() => ({
      pages: document.querySelectorAll('.page').length,
      clipped: [...document.querySelectorAll('.content')].filter((element) => element.scrollHeight > element.clientHeight + 1 || element.scrollWidth > element.clientWidth + 1).map((element) => element.closest('.page').getAttribute('aria-label')),
      images: [...document.images].filter((image) => !image.complete || !image.naturalWidth).map((image) => image.getAttribute('src')),
    }));
    if (errors.length || layout.pages !== 11 || layout.clipped.length || layout.images.length) throw new Error(JSON.stringify({ errors, layout }));
    await page.pdf({ path: path('brand/guide/ngen-brand-guide.pdf'), printBackground: true, preferCSSPageSize: true, tagged: true });
  } finally {
    try { await browser?.close(); } finally {
      if (server.pid && server.exitCode === null && server.signalCode === null) {
        const closed = once(server, 'close');
        server.kill();
        await closed;
      }
    }
  }
  for (let number = 1; number <= 11; number += 1) {
    const name = `ngen-guide-${String(number).padStart(2, '0')}`;
    await run('pdftocairo', ['-svg', '-f', String(number), '-l', String(number), path('brand/guide/ngen-brand-guide.pdf'), path(`brand/guide/pages/svg/${name}.svg`)]);
  }
  await run('pdftocairo', ['-png', '-r', '120', path('brand/guide/ngen-brand-guide.pdf'), path('brand/guide/pages/png/ngen-guide')]);
} finally { await rm(workspace, { recursive: true, force: true }); }
console.log(`Brand ${tokens.version}: both palettes, fonts, colored PNG/ICO exports, eleven-page PDF and page exports rebuilt.`);
